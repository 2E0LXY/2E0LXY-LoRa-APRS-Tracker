#!/usr/bin/env python3
"""Regenerate include/aprs_icons.h from the official aprs.fi symbol set.

Source: https://github.com/hessu/aprs-symbols  (png/aprs-symbols-128-{0,1,2}.png)
Usage:  tools/gen_aprs_icons.py /path/to/aprs-symbols/png

Output: 16x16 RGB565 icons, magenta (0xF81F) = transparent sentinel for TFT_eSPI pushImage().
  APRS_ICONS_PRIMARY[94]  primary table
  APRS_ICONS_ALT[94]      alternate table
  APRS_ICONS_OVERLAY[36]  overlay glyphs '0'-'9','A'-'Z' (composited over ALT at runtime)
"""
import sys
from PIL import Image

SIZE = 16
COLS = 16
TRANSPARENT = 0xF81F

def rgb565(r, g, b):
    v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return 0xF81E if v == TRANSPARENT else v        # never collide with the sentinel

def cell(sheet, idx):
    s = sheet.width // COLS
    x, y = (idx % COLS) * s, (idx // COLS) * s
    return sheet.crop((x, y, x + s, y + s))

def convert(im):
    # Premultiplied downscale avoids dark fringes from transparent-black texels.
    px = im.convert('RGBa').resize((SIZE, SIZE), Image.LANCZOS).convert('RGBA')
    out = []
    for r, g, b, a in px.getdata():
        out.append(TRANSPARENT if a < 112 else rgb565(r, g, b))
    return out

def emit(name, icons, count):
    lines = ['static const uint16_t %s[%s][256] PROGMEM = {' % (name, count)]
    for ic in icons:
        lines.append('  {' + ','.join(str(v) for v in ic) + '},')
    lines.append('};\n')
    return '\n'.join(lines)

def main(png_dir):
    sheets = [Image.open('%s/aprs-symbols-128-%d.png' % (png_dir, t)).convert('RGBA') for t in range(3)]
    prim = [convert(cell(sheets[0], i)) for i in range(94)]
    alt = [convert(cell(sheets[1], i)) for i in range(94)]
    ovl = [convert(cell(sheets[2], ord(c) - 33)) for c in '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ']
    hdr = '''#pragma once
#include <Arduino.h>

// Official APRS symbol icons for the on-device map view, generated by
// tools/gen_aprs_icons.py from the aprs.fi high-resolution symbol set by
// Heikki Hannikainen OH7LZB (https://github.com/hessu/aprs-symbols).
// Please keep this credit when redistributing; per-symbol licensing is in the
// upstream COPYRIGHT.md.
//
// 94 icons per table, 16x16 RGB565, magenta (0xF81F) is the transparent
// sentinel for TFT_eSPI pushImage(). Overlay glyphs ('0'-'9','A'-'Z') are drawn
// over the alternate-table symbol at runtime - see aprs_symbol_compose.h.
#define APRS_ICON_SIZE 16
#define APRS_ICON_TRANSPARENT 0xF81F
#define APRS_ICON_COUNT 94
#define APRS_OVERLAY_COUNT 36

'''
    open('include/aprs_icons.h', 'w').write(
        hdr + emit('APRS_ICONS_PRIMARY', prim, 'APRS_ICON_COUNT') + '\n' +
        emit('APRS_ICONS_ALT', alt, 'APRS_ICON_COUNT') + '\n' +
        emit('APRS_ICONS_OVERLAY', ovl, 'APRS_OVERLAY_COUNT'))

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '../aprs-symbols/png')
